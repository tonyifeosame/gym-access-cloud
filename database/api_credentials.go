// Integration credentials (migrations/030_api_credentials.sql).
//
// The fourth credential class, and the first one issued to somebody outside the
// company that runs the platform. Everything here is management: issuing,
// listing, rotating, revoking and reporting use. NOTHING IN THIS FILE IS
// REACHED BY A PUBLIC ROUTE, because there is no public route -- authentication
// is implemented and tested (AuthenticateAPICredential) so that the lifecycle
// can be proven before anything depends on it.
//
// THE SECRET EXISTS IN ONE LOCAL VARIABLE. generateAPIKey produces it, the hash
// goes to the database, and the plaintext is returned on the issue path and
// never stored, logged or re-read -- the same discipline generateSiteKey keeps
// for the site provisioning key.
//
// SHA-256 rather than bcrypt, for the reason already written in sites.go: 256
// bits from crypto/rand is not open to dictionary attack, does not need a slow
// KDF, and has to be verifiable on every request without burning CPU.

// HashAPIKey returns the stored form of an integration credential.
//
// Exported because the authentication path hashes what a caller presented before
// looking it up, and that has to be the same function that produced the stored
// value. Two spellings of "the hash" is how an authentication system stops
// authenticating.
func HashAPIKey(key string) string {
	sum := sha256.Sum256([]byte(key))
	return hex.EncodeToString(sum[:])
}

// generateAPIKey returns a new integration credential and its storage form.
//
// 32 bytes from crypto/rand. Not math/rand and not a UUID: a v4 UUID carries 122
// bits and is generated by libraries with varying opinions about entropy
// sources, which is not a thing to be casual about for a credential that reads a
// customer's roster.
func generateAPIKey(environment string) (key, hash, prefix string, err error) {
	if !models.APIEnvironments[environment] {
		return "", "", "", fmt.Errorf("%w: %q", models.ErrUnknownEnvironment, environment)
	}

	raw := make([]byte, 32)
	if _, err := rand.Read(raw); err != nil {
		return "", "", "", fmt.Errorf("generating integration credential: %w", err)
	}

	key = models.APIKeyClassPrefix + environment + "_" + hex.EncodeToString(raw)
	hash = HashAPIKey(key)
	prefix = key[:models.APIKeyPrefixLength] // non-secret, for display
	return key, hash, prefix, nil
}

