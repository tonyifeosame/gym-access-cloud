// AuthenticateAPICredential resolves a presented credential.
//
// NO ROUTE CALLS THIS YET. It exists in P1 so that the lifecycle above can be
// proven -- that a revoked credential stops working, that an expired one does,
// that a superseded one works until its grace window closes and not after -- by
// a test rather than by an assertion in a comment. The middleware that will use
// it belongs with the public routes, which do not exist.
//
// environment is the DEPLOYMENT's environment. A credential minted for the other
// one is refused by shape, before the database is touched: a staging key that
// reached production must fail immediately rather than miss a lookup and look
// like a typo.
//
// A DATABASE FAILURE IS NOT AN INVALID CREDENTIAL. It returns an error, and the
// caller must report it as a server fault -- the same reasoning AuthMiddleware
// applies to site keys and OperatorAuthMiddleware to sessions. Telling a caller
// its credential is invalid during an outage sends somebody looking for a
// credential problem that does not exist.
func AuthenticateAPICredential(presented, environment string) (*models.APICredentialIdentity, error) {
	if !models.ValidAPIKeyShape(presented) {
		return nil, nil
	}
	if models.APIKeyEnvironment(presented) != environment {
		return nil, nil
	}

	var (
		identity models.APICredentialIdentity
		scopes   pq.StringArray
	)
	err := DB.QueryRow(`
		SELECT c.id, c.public_id::text, c.company_id, c.name, c.key_prefix,
		       c.environment, c.scopes
		  FROM api_credentials c
		  JOIN companies co ON co.id = c.company_id
		 WHERE c.key_hash = $1
		   AND c.revoked_at IS NULL
		   AND (c.expires_at IS NULL OR c.expires_at > CURRENT_TIMESTAMP)
		   AND (c.superseded_at IS NULL OR c.grace_expires_at > CURRENT_TIMESTAMP)
		   AND co.active
		   AND co.deleted_at IS NULL`, HashAPIKey(presented)).
		Scan(&identity.ID, &identity.PublicID, &identity.CompanyID, &identity.Name,
			&identity.KeyPrefix, &identity.Environment, &scopes)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("authenticating integration credential: %w", err)
	}

	identity.Scopes = []string(scopes)

	siteIDs, err := credentialSiteIDs(identity.ID)
	if err != nil {
		return nil, err
	}
	identity.SiteIDs = siteIDs

	return &identity, nil
}

// credentialSiteIDs reads the site restriction. No rows means the whole company.
func credentialSiteIDs(credentialID int64) ([]int64, error) {
	rows, err := DB.Query(
		`SELECT site_id FROM api_credential_sites WHERE credential_id = $1`, credentialID)
	if err != nil {
		return nil, fmt.Errorf("reading credential sites: %w", err)
	}
	defer rows.Close()

	var ids []int64
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err != nil {
			return nil, fmt.Errorf("scanning credential site: %w", err)
		}
		ids = append(ids, id)
	}
	return ids, rows.Err()
}

// ---------------------------------------------------------------------------
// Usage telemetry
// ---------------------------------------------------------------------------
//
// LAST-USED IS NOT WRITTEN ON THE REQUEST PATH. A read-only API that writes a
// row to record that it was read has doubled its write load to store a value
// nobody reads in real time. Uses are accumulated in memory and flushed by the
// maintenance scheduler, so the cost is one statement per flush rather than one
// per request.
//
// NOTHING HERE CAN FAIL A REQUEST. NoteAPICredentialUse touches no database at
// all; a flush that fails is logged and retried on the next tick. That is the
// same trade WriteAuditEvent already makes, for the same reason: telemetry that
// takes the product down is telemetry somebody disables.

type credentialUse struct {
	at    time.Time
	ip    string
	byDay map[string]map[string]*usageCount // day -> class -> counts
}

type usageCount struct {
	requests int64
	refusals int64
}

var (
	credentialUseMu sync.Mutex
	credentialUses  = map[int64]*credentialUse{}
)

// NoteAPICredentialUse records that a credential served a request.
//
// refused says whether the request was turned away by the rate limiter; both are
// counted, because "this key is being refused constantly" is as useful an
// answer as "this key is busy".
func NoteAPICredentialUse(credentialID int64, ip, class string, at time.Time, refused bool) {
	if credentialID == 0 {
		return
	}

	credentialUseMu.Lock()
	defer credentialUseMu.Unlock()

	use, ok := credentialUses[credentialID]
	if !ok {
		use = &credentialUse{byDay: map[string]map[string]*usageCount{}}
		credentialUses[credentialID] = use
	}
	if at.After(use.at) {
		use.at = at
		if ip != "" {
			use.ip = ip
		}
	}

	if class == "" {
		return
	}
	day := at.UTC().Format("2006-01-02")
	classes, ok := use.byDay[day]
	if !ok {
		classes = map[string]*usageCount{}
		use.byDay[day] = classes
	}
	count, ok := classes[class]
	if !ok {
		count = &usageCount{}
		classes[class] = count
	}
	if refused {
		count.refusals++
	} else {
		count.requests++
	}
}

// FlushAPICredentialUse writes accumulated telemetry.
//
// Drains the buffer under the lock and writes outside it, so a slow database
// does not block the request path that is still recording uses.
func FlushAPICredentialUse(ctx context.Context) (int, error) {
	credentialUseMu.Lock()
	pending := credentialUses
	credentialUses = map[int64]*credentialUse{}
	credentialUseMu.Unlock()

	if len(pending) == 0 {
		return 0, nil
	}

	written := 0
	for credentialID, use := range pending {
		if !use.at.IsZero() {
			// GREATEST, so an out-of-order flush cannot move last_used_at
			// backwards. Two instances flushing concurrently is the normal case
			// once there is more than one.
			if _, err := DB.ExecContext(ctx, `
				UPDATE api_credentials
				   SET last_used_at = GREATEST(COALESCE(last_used_at, $2), $2),
				       last_used_ip = COALESCE(NULLIF($3, ''), last_used_ip)
				 WHERE id = $1`, credentialID, use.at, use.ip); err != nil {
				return written, fmt.Errorf("flushing credential use: %w", err)
			}
			written++
		}

		for day, classes := range use.byDay {
			for class, count := range classes {
				if _, err := DB.ExecContext(ctx, `
					INSERT INTO api_usage_daily (credential_id, day, class, requests, refusals)
					VALUES ($1, $2::date, $3, $4, $5)
					ON CONFLICT (credential_id, day, class) DO UPDATE
					   SET requests = api_usage_daily.requests + EXCLUDED.requests,
					       refusals = api_usage_daily.refusals + EXCLUDED.refusals`,
					credentialID, day, class, count.requests, count.refusals); err != nil {
					return written, fmt.Errorf("flushing credential usage: %w", err)
				}
			}
		}
	}
	return written, nil
}

// GetAPICredentialUsage reports recent use of one credential.
func GetAPICredentialUsage(companyID int64, publicID string, days int) (*models.APICredentialUsage, error) {
	if days <= 0 || days > 365 {
		days = 30
	}

	id, err := credentialRowID(DB, companyID, publicID)
	if err != nil {
		return nil, err
	}

	out := &models.APICredentialUsage{Days: []models.APICredentialUsageDay{}}

	var lastUsedAt sql.NullTime
	var lastUsedIP sql.NullString
	if err := DB.QueryRow(`
		SELECT public_id::text, name, key_prefix, last_used_at, last_used_ip
		  FROM api_credentials WHERE company_id = $1 AND id = $2`, companyID, id).
		Scan(&out.ID, &out.Name, &out.KeyPrefix, &lastUsedAt, &lastUsedIP); err != nil {
		return nil, fmt.Errorf("reading credential usage: %w", err)
	}
	if lastUsedAt.Valid {
		out.LastUsedAt = &lastUsedAt.Time
	}
	if lastUsedIP.Valid {
		out.LastUsedIP = lastUsedIP.String
	}

	rows, err := DB.Query(`
		SELECT to_char(day, 'YYYY-MM-DD'), class, requests, refusals
		  FROM api_usage_daily
		 WHERE credential_id = $1
		   AND day >= (CURRENT_DATE - $2::int)
		 ORDER BY day DESC, class`, id, days)
	if err != nil {
		return nil, fmt.Errorf("reading credential usage: %w", err)
	}
	defer rows.Close()

	for rows.Next() {
		var d models.APICredentialUsageDay
		if err := rows.Scan(&d.Day, &d.Class, &d.Requests, &d.Refusals); err != nil {
			return nil, fmt.Errorf("scanning credential usage: %w", err)
		}
		out.Days = append(out.Days, d)
	}
	return out, rows.Err()
}

// isUniqueViolation reports whether err is a unique index violation on the named
// constraint.
//
// Matching on the CONSTRAINT NAME rather than on the message text: the message
// is localised and version-dependent, and a substring match on it is how an
// error handler quietly stops recognising the case it was written for.
func isUniqueViolation(err error, constraint string) bool {
	var pqErr *pq.Error
	if !errors.As(err, &pqErr) {
		return false
	}
	return pqErr.Code == "23505" && pqErr.Constraint == constraint
}
