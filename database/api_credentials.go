const credentialColumns = `
	c.id, c.public_id, c.name, c.environment, c.key_prefix, c.scopes,
	c.created_by_email, c.created_at, c.expires_at,
	c.last_used_at, c.last_used_ip,
	c.superseded_at, c.grace_expires_at,
	c.revoked_at, c.revoked_reason,
	(SELECT u.email FROM users u WHERE u.id = c.revoked_by),
	(SELECT s.public_id::text FROM api_credentials s WHERE s.id = c.superseded_by)`

type credentialScan struct {
	id             int64
	publicID       string
	name           string
	environment    string
	keyPrefix      string
	scopes         pq.StringArray
	createdByEmail sql.NullString
	createdAt      time.Time
	expiresAt      sql.NullTime
	lastUsedAt     sql.NullTime
	lastUsedIP     sql.NullString
	supersededAt   sql.NullTime
	graceExpiresAt sql.NullTime
	revokedAt      sql.NullTime
	revokedReason  sql.NullString
	revokedByEmail sql.NullString
	supersededBy   sql.NullString
}

func (s *credentialScan) targets() []any {
	return []any{
		&s.id, &s.publicID, &s.name, &s.environment, &s.keyPrefix, &s.scopes,
		&s.createdByEmail, &s.createdAt, &s.expiresAt,
		&s.lastUsedAt, &s.lastUsedIP,
		&s.supersededAt, &s.graceExpiresAt,
		&s.revokedAt, &s.revokedReason,
		&s.revokedByEmail, &s.supersededBy,
	}
}

// credentialStatus resolves the lifecycle state a console renders.
//
// COMPUTED, NOT STORED. Four nullable timestamps describe the state between
// them, and a console asked to combine them is a console that will get it wrong
// once. The precedence is fixed here and is the same precedence the
// authentication predicate applies: revoked beats expired beats grace.
func credentialStatus(s *credentialScan, now time.Time) string {
	switch {
	case s.revokedAt.Valid:
		return models.APICredentialRevokedS
	case s.expiresAt.Valid && !s.expiresAt.Time.After(now):
		return models.APICredentialExpired
	case s.supersededAt.Valid:
		if s.graceExpiresAt.Valid && s.graceExpiresAt.Time.After(now) {
			return models.APICredentialInGrace
		}
		// Past its grace window. Not revoked and not expired, but it no longer
		// authenticates, and reporting it as ACTIVE would be a lie an operator
		// would act on.
		return models.APICredentialExpired
	default:
		return models.APICredentialActive
	}
}

func (s *credentialScan) toModel(now time.Time) *models.APICredential {
	out := &models.APICredential{
		ID:          s.publicID,
		Name:        s.name,
		Environment: s.environment,
		KeyPrefix:   s.keyPrefix,
		Scopes:      []string(s.scopes),
		Sites:       []models.SiteGrant{},
		AllSites:    true,
		CreatedAt:   s.createdAt,
		Status:      credentialStatus(s, now),
	}
	if s.scopes == nil {
		out.Scopes = []string{}
	}
	if s.createdByEmail.Valid {
		out.CreatedByEmail = s.createdByEmail.String
	}
	if s.expiresAt.Valid {
		out.ExpiresAt = &s.expiresAt.Time
	}
	if s.lastUsedAt.Valid {
		out.LastUsedAt = &s.lastUsedAt.Time
	}
	if s.lastUsedIP.Valid {
		out.LastUsedIP = s.lastUsedIP.String
	}
	if s.supersededAt.Valid {
		out.SupersededAt = &s.supersededAt.Time
	}
	if s.graceExpiresAt.Valid {
		out.GraceExpiresAt = &s.graceExpiresAt.Time
	}
	if s.revokedAt.Valid {
		out.RevokedAt = &s.revokedAt.Time
	}
	if s.revokedReason.Valid {
		out.RevokedReason = s.revokedReason.String
	}
	if s.revokedByEmail.Valid {
		out.RevokedByEmail = s.revokedByEmail.String
	}
	if s.supersededBy.Valid {
		out.SupersededByID = s.supersededBy.String
	}
	return out
}

// queryable is the subset of *sql.DB and *sql.Tx these readers need, so one
// implementation serves both a plain read and a read inside a transaction.
type queryable interface {
	Query(query string, args ...any) (*sql.Rows, error)
	QueryRow(query string, args ...any) *sql.Row
	Exec(query string, args ...any) (sql.Result, error)
}

// ListAPICredentials returns every credential in a company, newest first.
//
// Revoked and superseded rows are INCLUDED. "What integrations has this company
// ever had, and what happened to them" is the question an operator asks during a
// review, and a list that hid the revoked ones would answer a different one. The
// status field says which is which.
func ListAPICredentials(companyID int64) (*models.APICredentialList, error) {
	rows, err := DB.Query(`
		SELECT `+credentialColumns+`
		  FROM api_credentials c
		 WHERE c.company_id = $1
		 ORDER BY c.created_at DESC, c.id DESC`, companyID)
	if err != nil {
		return nil, fmt.Errorf("listing integration credentials: %w", err)
	}
	defer rows.Close()

	now := time.Now()
	out := &models.APICredentialList{Credentials: []models.APICredential{}}
	ids := []int64{}
	byID := map[int64]*models.APICredential{}

	for rows.Next() {
		var s credentialScan
		if err := rows.Scan(s.targets()...); err != nil {
			return nil, fmt.Errorf("scanning integration credential: %w", err)
		}
		credential := s.toModel(now)
		out.Credentials = append(out.Credentials, *credential)
		ids = append(ids, s.id)
		byID[s.id] = &out.Credentials[len(out.Credentials)-1]
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("listing integration credentials: %w", err)
	}

	if err := attachSiteGrants(DB, ids, byID); err != nil {
		return nil, err
	}

	out.Count = len(out.Credentials)
	return out, nil
}

// attachSiteGrants fills in the site restriction for a set of credentials.
//
// One query for the whole page rather than one per row: a console listing twenty
// credentials should not make twenty-one round trips, and the join is trivial.
func attachSiteGrants(q queryable, ids []int64, byID map[int64]*models.APICredential) error {
	if len(ids) == 0 {
		return nil
	}

	rows, err := q.Query(`
		SELECT acs.credential_id, s.public_id::text, s.site_name
		  FROM api_credential_sites acs
		  JOIN sites s ON s.id = acs.site_id
		 WHERE acs.credential_id = ANY($1)
		 ORDER BY s.site_name`, pq.Array(ids))
	if err != nil {
		return fmt.Errorf("reading credential site grants: %w", err)
	}
	defer rows.Close()

	for rows.Next() {
		var credentialID int64
		var grant models.SiteGrant
		if err := rows.Scan(&credentialID, &grant.SitePublicID, &grant.SiteName); err != nil {
			return fmt.Errorf("scanning credential site grant: %w", err)
		}
		if credential, ok := byID[credentialID]; ok {
			credential.Sites = append(credential.Sites, grant)
			credential.AllSites = false
		}
	}
	return rows.Err()
}

// GetAPICredential reads one credential inside a company.
func GetAPICredential(companyID int64, publicID string) (*models.APICredential, error) {
	return loadCredentialByPublicID(DB, companyID, publicID)
}

func loadCredentialByPublicID(q queryable, companyID int64, publicID string) (*models.APICredential, error) {
	id, err := credentialRowID(q, companyID, publicID)
	if err != nil {
		return nil, err
	}
	return loadCredential(q, companyID, id)
}

// credentialRowID resolves a public id INSIDE a company.
//
// Scoped by company in the same query rather than resolved and then checked:
// one query, one authorization, and no window in which the two can disagree.
// A credential in another company is ErrAPICredentialNotFound, exactly as one
// that never existed.
func credentialRowID(q queryable, companyID int64, publicID string) (int64, error) {
	trimmed := strings.TrimSpace(publicID)
	if trimmed == "" {
		return 0, models.ErrAPICredentialNotFound
	}

	var id int64
	err := q.QueryRow(`
		SELECT id FROM api_credentials
		 WHERE company_id = $1 AND public_id::text = $2`, companyID, trimmed).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, models.ErrAPICredentialNotFound
	}
	if err != nil {
		// A malformed UUID fails the cast rather than missing. Same answer: the
		// caller named something that is not one of their credentials.
		return 0, models.ErrAPICredentialNotFound
	}
	return id, nil
}

func loadCredential(q queryable, companyID, id int64) (*models.APICredential, error) {
	var s credentialScan
	err := q.QueryRow(`
		SELECT `+credentialColumns+`
		  FROM api_credentials c
		 WHERE c.company_id = $1 AND c.id = $2`, companyID, id).Scan(s.targets()...)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, models.ErrAPICredentialNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("reading integration credential: %w", err)
	}

	credential := s.toModel(time.Now())
	byID := map[int64]*models.APICredential{s.id: credential}
	if err := attachSiteGrants(q, []int64{s.id}, byID); err != nil {
		return nil, err
	}
	return credential, nil
}

func loadCredentialTx(tx *sql.Tx, companyID, id int64) (*models.APICredential, error) {
	return loadCredential(tx, companyID, id)
}

