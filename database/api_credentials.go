// RevokeAPICredential withdraws one credential permanently.
//
// Effective on the next request: the authentication path reads the row every
// time and nothing caches it, so there is no window in which a revoked
// credential still works. The row is kept, because the audit trail references
// it and because "what did this integration do before we turned it off" is the
// question somebody asks immediately afterwards.
func RevokeAPICredential(companyID int64, publicID, reason string,
	actorUserID int64) (*models.APICredential, error) {

	trimmed := strings.TrimSpace(reason)
	if trimmed == "" {
		trimmed = "revoked from the console"
	}
	if len(trimmed) > models.MaxAPICredentialReasonLength {
		trimmed = trimmed[:models.MaxAPICredentialReasonLength]
	}

	id, err := credentialRowID(DB, companyID, publicID)
	if err != nil {
		return nil, err
	}

	result, err := DB.Exec(`
		UPDATE api_credentials
		   SET revoked_at = CURRENT_TIMESTAMP,
		       revoked_by = NULLIF($3, 0)::bigint,
		       revoked_reason = $4
		 WHERE company_id = $1 AND id = $2 AND revoked_at IS NULL`,
		companyID, id, actorUserID, trimmed)
	if err != nil {
		return nil, fmt.Errorf("revoking integration credential: %w", err)
	}

	affected, err := result.RowsAffected()
	if err != nil {
		return nil, fmt.Errorf("revoking integration credential: %w", err)
	}
	if affected == 0 {
		// The row exists -- credentialRowID found it -- so the only way to
		// affect nothing is that it was already revoked. Idempotent would be
		// defensible; saying so is more useful, because a second revocation is
		// usually somebody unsure whether the first one worked.
		return nil, models.ErrAPICredentialRevoked
	}

	return loadCredential(DB, companyID, id)
}

// RevokeAllAPICredentials withdraws every live credential in a company.
//
// THE INCIDENT-RESPONSE CONTROL. One transaction, one audit record, one number
// to report. It matches rows that can still authenticate -- not revoked --
// including ones inside a rotation grace window, because "turn off every
// integration" must not leave the half of a rotation nobody was thinking about
// still working.
func RevokeAllAPICredentials(companyID int64, reason string, actorUserID int64) (int, error) {
	trimmed := strings.TrimSpace(reason)
	if trimmed == "" {
		trimmed = "bulk revocation from the console"
	}
	if len(trimmed) > models.MaxAPICredentialReasonLength {
		trimmed = trimmed[:models.MaxAPICredentialReasonLength]
	}

	result, err := DB.Exec(`
		UPDATE api_credentials
		   SET revoked_at = CURRENT_TIMESTAMP,
		       revoked_by = NULLIF($2, 0)::bigint,
		       revoked_reason = $3
		 WHERE company_id = $1 AND revoked_at IS NULL`,
		companyID, actorUserID, trimmed)
	if err != nil {
		return 0, fmt.Errorf("revoking integration credentials: %w", err)
	}

	affected, err := result.RowsAffected()
	if err != nil {
		return 0, fmt.Errorf("revoking integration credentials: %w", err)
	}
	return int(affected), nil
}

