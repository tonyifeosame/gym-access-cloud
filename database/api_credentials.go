// RotateAPICredential supersedes a credential and issues its replacement.
//
// A NEW ROW, NOT A NEW HASH ON THE OLD ONE. The integrator needs an overlap in
// which to deploy; replacing the hash in place forces a simultaneous cutover
// that will be done badly at two in the morning. Both credentials authenticate
// until grace_expires_at, and a grace of zero is an immediate cutover -- which
// is the right choice when the reason for rotating is that the old one leaked.
//
// The name, scopes, environment and site restriction are carried over. Changing
// what an integration may do is a separate decision from replacing its secret,
// and bundling the two would mean an emergency rotation is also an opportunity
// to fat-finger a scope.
func RotateAPICredential(companyID int64, publicID string, grace time.Duration,
	actorUserID int64, actorEmail string) (*models.APICredentialIssued, error) {

	if grace < 0 {
		grace = 0
	}
	if grace > models.MaxAPIKeyRotationGrace {
		return nil, models.ErrAPIKeyGraceTooLong
	}

	tx, err := DB.Begin()
	if err != nil {
		return nil, fmt.Errorf("rotating integration credential: %w", err)
	}
	defer tx.Rollback()

	if err := lockCompanyCredentials(tx, companyID); err != nil {
		return nil, err
	}

	oldID, err := credentialRowID(tx, companyID, publicID)
	if err != nil {
		return nil, err
	}

	var (
		name         string
		environment  string
		scopes       pq.StringArray
		expiresAt    sql.NullTime
		revokedAt    sql.NullTime
		supersededAt sql.NullTime
	)
	err = tx.QueryRow(`
		SELECT name, environment, scopes, expires_at, revoked_at, superseded_at
		  FROM api_credentials
		 WHERE company_id = $1 AND id = $2
		 FOR UPDATE`, companyID, oldID).
		Scan(&name, &environment, &scopes, &expiresAt, &revokedAt, &supersededAt)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, models.ErrAPICredentialNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("reading credential for rotation: %w", err)
	}

	if revokedAt.Valid {
		return nil, models.ErrAPICredentialRevoked
	}
	// Rotating an already-superseded row would branch the chain and leave two
	// replacements for one original, with nothing to say which is current.
	if supersededAt.Valid {
		return nil, models.ErrAPICredentialSuperseded
	}

	key, hash, prefix, err := generateAPIKey(environment)
	if err != nil {
		return nil, err
	}

	// ORDER MATTERS. The old row leaves api_credentials_company_name_live as
	// soon as superseded_at is set, which is what lets the replacement enter the
	// index under the same name inside this transaction.
	graceExpiry := time.Now().Add(grace)
	if _, err := tx.Exec(`
		UPDATE api_credentials
		   SET superseded_at = CURRENT_TIMESTAMP, grace_expires_at = $3
		 WHERE company_id = $1 AND id = $2`, companyID, oldID, graceExpiry); err != nil {
		return nil, fmt.Errorf("superseding integration credential: %w", err)
	}

	var newID int64
	err = tx.QueryRow(`
		INSERT INTO api_credentials
		    (company_id, name, environment, key_hash, key_prefix, scopes,
		     created_by, created_by_email, expires_at)
		VALUES ($1, $2, $3, $4, $5, $6,
		        NULLIF($7, 0)::bigint, NULLIF($8, ''), $9)
		RETURNING id`,
		companyID, name, environment, hash, prefix, scopes,
		actorUserID, actorEmail, nullTime(expiresAt)).Scan(&newID)
	if err != nil {
		return nil, fmt.Errorf("inserting rotated credential: %w", err)
	}

	if _, err := tx.Exec(`
		UPDATE api_credentials SET superseded_by = $3
		 WHERE company_id = $1 AND id = $2`, companyID, oldID, newID); err != nil {
		return nil, fmt.Errorf("linking rotated credential: %w", err)
	}

	// The site restriction is part of what the credential IS, so it moves with
	// the name and the scopes.
	if _, err := tx.Exec(`
		INSERT INTO api_credential_sites (credential_id, site_id)
		SELECT $2, site_id FROM api_credential_sites WHERE credential_id = $1`,
		oldID, newID); err != nil {
		return nil, fmt.Errorf("copying credential sites: %w", err)
	}

	credential, err := loadCredentialTx(tx, companyID, newID)
	if err != nil {
		return nil, err
	}

	if err := tx.Commit(); err != nil {
		return nil, fmt.Errorf("committing credential rotation: %w", err)
	}

	return &models.APICredentialIssued{
		APICredential: *credential,
		Secret:        key,
		ShownOnce:     true,
	}, nil
}

func nullTime(t sql.NullTime) any {
	if !t.Valid {
		return nil
	}
	return t.Time
}

