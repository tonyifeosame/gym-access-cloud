// APICredentialIssueInput is what the console supplies to mint one.
type APICredentialIssueInput struct {
	CompanyID int64

	Name        string
	Environment string
	// Scopes must already be expanded and validated by the caller. The store
	// re-checks that every one is known, because the database CHECK would
	// otherwise be the only thing standing between a typo and a stored scope
	// nothing can interpret.
	Scopes []string
	// SitePublicIDs restricts the credential. Empty means every site in the
	// company, now and in future.
	SitePublicIDs []string

	// ExpiresAt nil means never. The caller applies the default lifetime; the
	// store does not invent one, so "never" stays expressible.
	ExpiresAt *time.Time

	ActorUserID int64
	ActorEmail  string
}

// IssueAPICredential mints a credential and returns its plaintext ONCE.
//
// THE PER-COMPANY CAP IS ENFORCED UNDER AN ADVISORY LOCK. PostgreSQL cannot
// express "at most twenty rows per company" as a constraint -- a CHECK cannot
// see other rows and a unique index cannot count -- so two concurrent issues
// could each count nineteen and both insert. pg_advisory_xact_lock serialises
// the count-and-insert for one company and is released by the commit, so the
// window does not exist. Namespace 30 is this migration's number, so the lock
// cannot collide with an unrelated advisory lock taken elsewhere later.
//
// THE COUNT EXCLUDES SUPERSEDED ROWS. A credential in its rotation grace window
// still authenticates but does not occupy a slot, so a company at the cap can
// still rotate. A cap that deadlocks the operation somebody reaches for during
// an incident is worse than no cap.
func IssueAPICredential(in APICredentialIssueInput) (*models.APICredentialIssued, error) {
	for _, scope := range in.Scopes {
		if !models.KnownScope(scope) {
			return nil, fmt.Errorf("%w: %q", models.ErrUnknownScope, scope)
		}
	}
	if len(in.Scopes) == 0 {
		return nil, models.ErrNoScopes
	}

	name, err := models.ValidateAPICredentialName(in.Name)
	if err != nil {
		return nil, err
	}

	if in.ExpiresAt != nil && !in.ExpiresAt.After(time.Now()) {
		return nil, models.ErrAPICredentialExpiryInPast
	}

	key, hash, prefix, err := generateAPIKey(in.Environment)
	if err != nil {
		return nil, err
	}

	tx, err := DB.Begin()
	if err != nil {
		return nil, fmt.Errorf("issuing integration credential: %w", err)
	}
	defer tx.Rollback()

	if err := lockCompanyCredentials(tx, in.CompanyID); err != nil {
		return nil, err
	}

	if err := assertCredentialHeadroom(tx, in.CompanyID); err != nil {
		return nil, err
	}

	siteIDs, err := resolveCredentialSites(tx, in.CompanyID, in.SitePublicIDs)
	if err != nil {
		return nil, err
	}

	var id int64
	err = tx.QueryRow(`
		INSERT INTO api_credentials
		    (company_id, name, environment, key_hash, key_prefix, scopes,
		     created_by, created_by_email, expires_at)
		VALUES ($1, $2, $3, $4, $5, $6,
		        NULLIF($7, 0)::bigint, NULLIF($8, ''), $9)
		RETURNING id`,
		in.CompanyID, name, in.Environment, hash, prefix, pq.Array(in.Scopes),
		in.ActorUserID, in.ActorEmail, in.ExpiresAt).Scan(&id)
	if err != nil {
		if isUniqueViolation(err, "api_credentials_company_name_live") {
			return nil, models.ErrAPICredentialNameTaken
		}
		return nil, fmt.Errorf("inserting integration credential: %w", err)
	}

	if err := attachCredentialSites(tx, id, siteIDs); err != nil {
		return nil, err
	}

	credential, err := loadCredentialTx(tx, in.CompanyID, id)
	if err != nil {
		return nil, err
	}

	if err := tx.Commit(); err != nil {
		return nil, fmt.Errorf("committing integration credential: %w", err)
	}

	return &models.APICredentialIssued{
		APICredential: *credential,
		Secret:        key,
		ShownOnce:     true,
	}, nil
}

// lockCompanyCredentials serialises credential mutation for one company.
//
// Two integers rather than one bigint so the namespace is explicit and this lock
// cannot be confused with an unrelated one taken on the same company id
// elsewhere. Released by the transaction, so nothing has to remember to unlock.
func lockCompanyCredentials(tx *sql.Tx, companyID int64) error {
	if _, err := tx.Exec(`SELECT pg_advisory_xact_lock(30, $1::int)`, companyID); err != nil {
		return fmt.Errorf("locking company credentials: %w", err)
	}
	return nil
}

// assertCredentialHeadroom refuses a company that is already at the cap.
func assertCredentialHeadroom(tx *sql.Tx, companyID int64) error {
	var live int
	err := tx.QueryRow(`
		SELECT count(*) FROM api_credentials
		 WHERE company_id = $1
		   AND revoked_at IS NULL
		   AND superseded_at IS NULL`, companyID).Scan(&live)
	if err != nil {
		return fmt.Errorf("counting integration credentials: %w", err)
	}
	if live >= models.MaxAPICredentialsPerCompany {
		return models.ErrAPICredentialLimit
	}
	return nil
}

// resolveCredentialSites turns site public ids into row ids, INSIDE the company.
//
// A site in another company does not resolve, and the error says the site is not
// in this company rather than that it does not exist -- the caller is an
// authenticated ADMIN of this tenant, so there is nothing to conceal from them
// about their own account, and a vaguer message would send them looking for a
// typo in an id that is real.
func resolveCredentialSites(tx *sql.Tx, companyID int64, publicIDs []string) ([]int64, error) {
	if len(publicIDs) == 0 {
		return nil, nil
	}

	cleaned := make([]string, 0, len(publicIDs))
	for _, id := range publicIDs {
		if trimmed := strings.TrimSpace(id); trimmed != "" {
			cleaned = append(cleaned, trimmed)
		}
	}
	if len(cleaned) == 0 {
		return nil, nil
	}

	rows, err := tx.Query(`
		SELECT id FROM sites
		 WHERE company_id = $1
		   AND deleted_at IS NULL
		   AND public_id::text = ANY($2)`, companyID, pq.Array(cleaned))
	if err != nil {
		// A malformed UUID reaches here as a cast error rather than as no rows.
		// It is the same answer either way: a site the caller named is not one
		// of theirs.
		return nil, models.ErrAPICredentialSiteUnknown
	}
	defer rows.Close()

	var ids []int64
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err != nil {
			return nil, fmt.Errorf("resolving credential sites: %w", err)
		}
		ids = append(ids, id)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("resolving credential sites: %w", err)
	}

	// Every named site must have resolved. Silently dropping one would produce a
	// credential scoped more narrowly than the operator believes, which is the
	// direction that fails closed but still lies to them.
	if len(ids) != len(dedupe(cleaned)) {
		return nil, models.ErrAPICredentialSiteUnknown
	}
	return ids, nil
}

func dedupe(values []string) []string {
	seen := make(map[string]bool, len(values))
	out := make([]string, 0, len(values))
	for _, v := range values {
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	return out
}

func attachCredentialSites(tx *sql.Tx, credentialID int64, siteIDs []int64) error {
	for _, siteID := range siteIDs {
		if _, err := tx.Exec(`
			INSERT INTO api_credential_sites (credential_id, site_id)
			VALUES ($1, $2) ON CONFLICT DO NOTHING`, credentialID, siteID); err != nil {
			return fmt.Errorf("attaching credential site: %w", err)
		}
	}
	return nil
}

